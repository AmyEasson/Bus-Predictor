#!/usr/bin/env python3
"""
build_pairs.py - turn stop arrivals into training examples for the delay model.

Each example asks:
    "A bus is at stop i right now, D seconds late. How late will it be at stop j further along?"

Built to scale to the whole Greater Manchester network over many weeks:
  * accepts SEVERAL stop_arrivals files (e.g. one per archive week) and processes them one at a
    time, so memory is bounded by the largest single file, not the whole dataset;
  * the total number of possible pairs is counted first (cheaply, from run lengths), and one
    sampling fraction is applied everywhere, so the --max-pairs sample is spread evenly over all
    weeks and routes;
  * the "last 30 minutes" live-feature tables are computed ONCE per file, not once per batch;
  * pairs are generated by shifting within each journey (no many-to-many merge) in small
    batches and streamed to Parquet via a temp file, so a failed run never leaves a
    half-written training set behind.

Usage (from the project root):
    python3 delay_engine/model/build_pairs.py \
        --arrivals "/tmp/bods_batches_working_copy/week_*/stop_arrivals.parquet" \
        --gtfs data/ --context context/ --out delay_engine/model/out/pairs.parquet

--arrivals takes one or more paths and/or glob patterns (quote globs).
"""

import argparse
import glob
import os
import sys

import numpy as np
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import features as F  # noqa: E402

MAX_STOPS_AHEAD = 15        # predict up to 15 stops ahead (~15-25 min)
MAX_PAIRS = 3_000_000       # cap on training examples (lower it if memory runs out)
RUN_CHUNK = 500             # journeys per pair-generation batch


def expand_paths(items):
    paths = []
    for item in items:
        matches = sorted(glob.glob(item))
        paths.extend(matches if matches else [item])
    paths = [p for p in paths if os.path.exists(p)]
    # skip empty weeks (e.g. before the timetable matched); .sqlite inputs are kept as they are
    paths = [p for p in paths if not p.endswith(".parquet") or pq.read_metadata(p).num_rows > 0]
    if not paths:
        raise SystemExit(f"no non-empty arrivals files found for {items}")
    return paths


def count_pairs(run_lengths):
    """Number of (i, j) pairs, j within MAX_STOPS_AHEAD of i, for journeys of these lengths."""
    n = np.asarray(run_lengths)
    return int(sum(np.clip(n - ahead, 0, None).sum() for ahead in range(1, MAX_STOPS_AHEAD + 1)))


def estimate_total_pairs(paths):
    """Cheap pre-pass: read only the run-key columns of each file. arrivals.py already drops the
    first stop; the model also drops the last stop, hence length - 1."""
    total = 0
    for p in paths:
        if not p.endswith(".parquet"):
            continue
        k = pd.read_parquet(p, columns=["service_date", "operator_ref", "vehicle_ref", "trip_id"])
        lengths = k.groupby(list(k.columns), dropna=False).size() - 1
        total += count_pairs(lengths)
    return total


def generate_pair_batches(sa, fraction, rng):
    """Yield sampled training pairs, RUN_CHUNK journeys at a time."""
    # Terminus stops are unreliable (waiting / padded schedules): never a start or a target
    sa = sa[(sa.is_first_stop == 0) & (sa.is_last_stop == 0)].reset_index(drop=True)
    run_ids = sa["run_id"].drop_duplicates().to_numpy()
    for start in range(0, len(run_ids), RUN_CHUNK):
        chunk = sa[sa["run_id"].isin(run_ids[start:start + RUN_CHUNK])].reset_index(drop=True)
        pairs = _pairs_for(chunk)
        if len(pairs) and fraction < 1:
            pairs = pairs.loc[rng.random(len(pairs)) < fraction].reset_index(drop=True)
        if len(pairs):
            yield pairs


def _pairs_for(sa):
    """All forward pairs within each journey, by shifting the target stop 1..15 places along."""
    left_columns = ["run_id", "route_short_name", "direction_id", "stop_id", "actual_utc",
                    "scheduled_utc", "delay_s", "gap_ahead_s", "headway_ratio"]
    right_columns = ["stop_id", "scheduled_utc", "actual_utc", "delay_s", "stop_lat", "stop_lon"]
    left_names = {"stop_id": "from_stop", "actual_utc": "now_utc", "scheduled_utc": "sched_from",
                  "delay_s": "delay_now_s", "route_short_name": "route",
                  "direction_id": "direction"}
    right_names = {"stop_id": "to_stop", "scheduled_utc": "sched_to", "actual_utc": "actual_to",
                   "delay_s": "target_delay_s", "stop_lat": "to_lat", "stop_lon": "to_lon"}

    grouped = sa.groupby("run_id", sort=False)
    positions = grouped.cumcount()
    run_sizes = grouped["run_id"].transform("size")
    parts = []
    for ahead in range(1, MAX_STOPS_AHEAD + 1):
        valid = positions + ahead < run_sizes
        if not valid.any():
            continue
        left = sa.loc[valid, left_columns].rename(columns=left_names).reset_index(drop=True)
        right = grouped[right_columns].shift(-ahead).loc[valid] \
            .rename(columns=right_names).reset_index(drop=True)
        p = pd.concat([left, right], axis=1)
        p["stops_ahead"] = ahead
        p["sched_travel_s"] = (p["sched_to"] - p["sched_from"]).dt.total_seconds()
        parts.append(p.drop(columns=["sched_from"]))
    return pd.concat(parts, ignore_index=True) if parts else pd.DataFrame()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arrivals", nargs="+",
                    default=["delay_engine/trip_matching/out/stop_arrivals.parquet"],
                    help="one or more stop_arrivals.parquet files or glob patterns")
    ap.add_argument("--gtfs", default="data/", help="folder with the GTFS .parquet tables")
    ap.add_argument("--context", default="context/")
    ap.add_argument("--out", default="delay_engine/model/out/pairs.parquet")
    ap.add_argument("--max-pairs", type=int, default=MAX_PAIRS)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    if a.max_pairs < 1:
        ap.error("--max-pairs must be at least 1")

    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    temp_out = a.out + ".tmp"
    for f in (temp_out, a.out):
        if os.path.exists(f):
            os.remove(f)          # never leave a stale or partial file for train.py

    paths = expand_paths(a.arrivals)
    total = estimate_total_pairs(paths)
    fraction = min(1.0, a.max_pairs / max(total, 1))
    print(f"{len(paths)} arrivals file(s) | ~{total:,} possible pairs -> keeping "
          f"{fraction:.2%} (cap {a.max_pairs:,})")

    context_hourly = F.load_context_hourly(os.path.join(a.context, "context_hourly.parquet"))
    events = F.load_events(os.path.join(a.context, "events.csv"))
    if context_hourly is None:
        print(f"WARNING: no context_hourly.parquet in {a.context} - weather/calendar/events empty")
    rng = np.random.default_rng(a.seed)

    writer, written = None, 0
    filled = {"weather": [], "calendar": [], "events": [], "live": []}
    try:
        for i, path in enumerate(paths, 1):
            sa = F.load_stop_arrivals(path, a.gtfs)
            tables = F.live_tables(sa)           # once per file, reused for every batch
            n_file = 0
            for p in generate_pair_batches(sa, fraction, rng):
                p = F.add_time_features(p, "now_utc")
                p = F.add_live_features(p, ts_col="now_utc", tables=tables)
                p = F.add_hourly_context(p, context_hourly, "now_utc")
                p = F.add_events(p, events, "now_utc")
                for c in p.select_dtypes("float64").columns:
                    p[c] = p[c].astype("float32")

                for name, cols in [("weather", F.WEATHER), ("calendar", F.CALENDAR),
                                   ("events", ["event_active"]), ("live", F.LIVE)]:
                    filled[name].append((p[cols].notna().mean().mean(), len(p)))

                table = pa.Table.from_pandas(p, preserve_index=False)
                if writer is None:
                    writer = pq.ParquetWriter(temp_out, table.schema, compression="snappy")
                else:
                    table = table.cast(writer.schema)
                writer.write_table(table)
                written += len(p)
                n_file += len(p)
            print(f"[{i}/{len(paths)}] {os.path.basename(os.path.dirname(path)) or path}: "
                  f"{len(sa):,} arrivals, {sa.run_id.nunique():,} journeys -> {n_file:,} pairs "
                  f"(total {written:,})", flush=True)
            del sa, tables

        if writer is not None:
            writer.close()
            writer = None
        if written == 0:
            raise ValueError("No training pairs were generated.")
        os.replace(temp_out, a.out)
    except BaseException:
        if writer is not None:
            writer.close()
        if os.path.exists(temp_out):
            os.remove(temp_out)
        raise

    print("\nfeature coverage (share of values present):")
    for name, vals in filled.items():
        share = sum(v * n for v, n in vals) / max(sum(n for _, n in vals), 1)
        print(f"  {name:9s}: {share:.0%}")
    print(f"\nwrote {written:,} pairs -> {a.out}")


if __name__ == "__main__":
    main()