"""Turn the GTFS parquet tables into two small lookup tables.

  trip_starts.parquet   one row per trip: line, first stop, scheduled first departure
  service_days.parquet  one row per (service_id, date) the service actually runs

Usage:
  python3 prep_timetable.py --gtfs-dir path/to/parquet --out-dir out
"""
import argparse
from pathlib import Path
import pandas as pd

_WEEKDAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]


def read(gtfs_dir, name, cols=None):
    return pd.read_parquet(Path(gtfs_dir) / f"{name}.parquet", columns=cols)


def build_trip_starts(gtfs_dir):
    # dep_s is a pre-processed column (seconds after midnight); standard GTFS stores
    # departure_time as "HH:MM:SS". The parquet files must be generated by a script
    # that converts departure_time to dep_s before writing.
    st = read(gtfs_dir, "stop_times", [
              "trip_id", "stop_sequence", "stop_id", "dep_s"])
    # first stop of each trip = lowest stop_sequence (sequence starts at 0, not 1)
    first = st.loc[st.groupby("trip_id")["stop_sequence"].idxmin()]
    first = first.rename(columns={"stop_id": "first_stop_id"})[
        ["trip_id", "first_stop_id", "dep_s"]]

    trips = read(gtfs_dir, "trips")
    keep = [c for c in ["trip_id", "route_id", "service_id", "trip_headsign",
                        "direction_id", "vehicle_journey_code"] if c in trips.columns]
    routes = read(gtfs_dir, "routes")
    rkeep = [c for c in ["route_id", "route_short_name",
                         "agency_id", "route_type"] if c in routes.columns]
    out = first.merge(trips[keep], on="trip_id").merge(
        routes[rkeep], on="route_id")
    if "route_type" in out:  # 3 = bus
        out = out[out.route_type.astype(str) == "3"]
    out["route_short_name"] = out["route_short_name"].astype(str).str.strip()
    return out.reset_index(drop=True)


def build_service_days(gtfs_dir):
    cal = read(gtfs_dir, "calendar")
    for c in _WEEKDAYS:
        cal[c] = pd.to_numeric(cal[c]).fillna(0).astype(int)
    for c in ("start_date", "end_date"):
        cal[c] = pd.to_datetime(cal[c].astype(str), format="%Y%m%d")
    rows = []
    # itertuples loop is O(services × date-range length); fine for typical GTFS sizes
    for r in cal.itertuples(index=False):
        rng = pd.date_range(r.start_date, r.end_date, freq="D")
        ok = rng[[bool(getattr(r, _WEEKDAYS[d.weekday()])) for d in rng]]
        rows.append(pd.DataFrame({"service_id": r.service_id, "date": ok}))
    base = pd.concat(rows, ignore_index=True) if rows else pd.DataFrame(
        columns=["service_id", "date"])

    cd = read(gtfs_dir, "calendar_dates")
    cd["exception_type"] = pd.to_numeric(cd["exception_type"])
    cd["date"] = pd.to_datetime(cd["date"].astype(str), format="%Y%m%d")
    removed = cd[cd.exception_type == 2][["service_id", "date"]]
    added = cd[cd.exception_type == 1][["service_id", "date"]]
    base = base.merge(removed.assign(_rm=1), how="left",
                      on=["service_id", "date"])
    base = base[base["_rm"].isna()].drop(columns="_rm")
    out = pd.concat([base, added], ignore_index=True).drop_duplicates()
    # 'YYYY-MM-DD', same as data_frame_ref
    out["date"] = out["date"].dt.date.astype(str)
    return out.reset_index(drop=True)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--gtfs-dir", required=True,
                    help="folder with trips/stop_times/... .parquet")
    ap.add_argument("--out-dir", default="out")
    a = ap.parse_args()
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    ts = build_trip_starts(a.gtfs_dir)
    ts.to_parquet(out / "trip_starts.parquet", index=False)
    sd = build_service_days(a.gtfs_dir)
    sd.to_parquet(out / "service_days.parquet", index=False)
    print(
        f"trip_starts: {len(ts):,} trips | service_days: {len(sd):,} (service, date) rows")
